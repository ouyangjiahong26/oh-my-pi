def _policy_settings() -> RobompSettings:

    return RobompSettings.model_construct(triage_policy=triage_policy.CISLUNARSPACE)


def test_question_does_not_add_type_or_upstream_labels() -> None:
    labels = triage_policy.labels_for_issue("question", [], ["type/research", "needs-info"])
    assert labels == []


def test_question_preserves_existing_template_labels() -> None:
    labels = triage_policy.labels_for_issue("question", ["area/glossary"], ["type/task", "needs-triage"])
    assert labels == ["area/glossary"]


def test_bug_preserves_template_type_and_adds_evidence_area() -> None:
    labels = triage_policy.labels_for_issue("bug", ["area/glossary"], ["type/bug", "needs-triage"])
    assert labels == ["area/glossary"]


def test_documentation_maps_to_task_only_when_type_missing() -> None:
    labels = triage_policy.labels_for_issue("documentation", [], [])
    assert labels == ["type/task"]


def test_unclassified_question_does_not_invent_type() -> None:
    labels = triage_policy.labels_for_issue("question", ["area/web"], [])
    assert labels == ["area/web"]


def test_unknown_areas_are_dropped() -> None:
    labels = triage_policy.labels_for_issue("bug", ["tool", "agent", "area/glossary"], [])
    assert labels == ["type/bug", "area/glossary"]


def test_pr_labels_use_repository_kind_and_area() -> None:
    assert triage_policy.labels_for_pr("fix", ["area/web", "tool"]) == ["kind/bug-fix", "area/web"]


def test_upstream_labels_remain_upstream() -> None:
    assert triage_policy.allowed_labels(["bug", "prio:p1", "tool"], "upstream") == ["bug", "prio:p1", "tool"]


def test_cislunarspace_labels_filter_upstream_vocabulary() -> None:
    assert triage_policy.allowed_labels(
        ["bug", "prio:p1", "type/bug", "area/web", "triaged", "needs-triage"], triage_policy.CISLUNARSPACE
    ) == ["type/bug", "area/web", "needs-triage"]


def test_pr_text_requires_ai_marker_tool_and_closes() -> None:
    title = "[AI Generated][FIX] 修复 L1 描述"
    good = "generated by AI，工具 omp\n\nCloses #42\n\n问题、方案、验证"
    assert triage_policy.validate_pr_text(title, good, 42, triage_policy.CISLUNARSPACE) is None
    assert triage_policy.validate_pr_text(
        title, good.replace("generated by AI，工具 omp", ""), 42, triage_policy.CISLUNARSPACE
    )
    assert triage_policy.validate_pr_text(title, good.replace("Closes #42", ""), 42, triage_policy.CISLUNARSPACE)


