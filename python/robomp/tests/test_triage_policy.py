def test_cislunarspace_bug_applies_only_mapped_labels(db: Database, tmp_path: Path) -> None:
    captured: dict[str, object] = {}

    def handler(request: httpx.Request) -> httpx.Response:
        captured["body"] = json.loads(request.content)
        return httpx.Response(200, json=[{"name": n} for n in captured["body"]["labels"]])

    bindings, loop, thread = _bindings(db, tmp_path, httpx.MockTransport(handler))
    try:
        bindings = replace(bindings, settings=_policy_settings())
        tool = next(x for x in host_tools.build(bindings) if x.name == "classify_issue")
        result = tool.execute(
            {
                "primary": "bug",
                "priority": "prio:p1",
                "areas": ["area/glossary"],
                "rationale": "documented defect",
            },
            _ctx(),
        )
    finally:
        _stop_loop(loop, thread)
    assert captured["body"]["labels"] == ["type/bug", "area/glossary"]
    assert "classified as bug" in result


