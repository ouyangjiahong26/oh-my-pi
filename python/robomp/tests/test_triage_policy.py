def test_cislunarspace_pr_body_does_not_require_upstream_sections(db: Database, tmp_path: Path) -> None:
    bindings, loop, thread = _bindings(db, tmp_path, httpx.MockTransport(lambda _r: httpx.Response(500)))
    try:
        bindings = replace(
            bindings,
            settings=_policy_settings(),
            impl_authorized=True,
        )
        db.set_issue_classification(bindings.issue_key, "bug")
        tool = next(x for x in host_tools.build(bindings) if x.name == "gh_open_pr")
        with pytest.raises(RpcCommandError) as exc:
            tool.execute(
                {
                    "title": "[AI Generated][FIX] 修复 L1 描述",
                    "body": "generated by AI，工具 omp\n\n问题、原因、修改和验证。",
                },
                _ctx(),
            )
        assert "Closes #42" in str(exc.value)
        assert "Repro" not in str(exc.value)
    finally:
        _stop_loop(loop, thread)


@pytest.mark.asyncio
async def test_unauthorized_bug_uses_read_only_rpc_tools(
    tmp_path: Path, settings: RobompSettings, monkeypatch: pytest.MonkeyPatch
) -> None:

    from robomp import worker

    monkeypatch.setattr("robomp.worker.host_tools.build", lambda _b: ())
    settings.triage_policy = triage_policy.CISLUNARSPACE
    inputs, bindings = _make_inputs(tmp_path, settings, session_has_jsonl=False)
    bindings.db = inputs.db
    bindings.settings = settings
    bindings.impl_authorized = False
    inputs.db.get_issue = lambda _key: SimpleNamespace(classification="bug", pr_number=None)
    bindings.db.has_authorized_impl_event = lambda _key: False
    loop = asyncio.new_event_loop()
    try:
        worker._run_rpc_blocking(inputs, task_kind="triage_issue", prompt="kickoff", loop=loop, bindings=bindings)
    finally:
        loop.close()
    assert _FakeRpcClient.instances[0].kwargs["tools"] == ("read", "grep", "glob", "bash", "todo")


