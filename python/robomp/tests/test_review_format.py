"""Unit tests for review summary reconciliation."""

from __future__ import annotations

from robomp.review_format import (
    count_severities,
    format_counts,
    reconcile_verdict_counts,
    severity_of,
    strip_ai_footer,
)


def test_severity_of_recognises_each_prefix() -> None:
    assert severity_of("阻塞项：第 42 行解引用空指针。") == "阻塞"
    assert severity_of("应改项：第 7 行用了加粗。") == "应改"
    assert severity_of("建议：第 11 行的概括与现状不符。") == "建议"
    assert severity_of("  阻塞项：缩进后仍算阻塞。") == "阻塞"


def test_severity_of_falls_back_to_should_fix() -> None:
    assert severity_of("这条评论没有写严重级别前缀。") == "应改"
    assert severity_of("") == "应改"


def test_count_severities_tallies_in_prompt_order() -> None:
    counts = count_severities(
        [
            "应改项：a",
            "阻塞项：b",
            "建议：c",
            "无前缀",
            "阻塞项：e",
        ]
    )
    assert counts == {"阻塞": 2, "应改": 2, "建议": 1}


def test_format_counts_omits_empty_severities() -> None:
    assert format_counts({"阻塞": 1, "应改": 0, "建议": 0}) == "1 条阻塞"
    assert format_counts({"阻塞": 0, "应改": 0, "建议": 0}) == ""
    assert format_counts({"阻塞": 2, "应改": 3, "建议": 1}) == "2 条阻塞、3 条应改、1 条建议"


def test_reconcile_corrects_undercounted_verdict() -> None:
    # The exact failure seen on the format-sample PR: the model said two
    # should-fix items while listing three.
    body = (
        "## 结论\n"
        "评级 P3，1 条阻塞、2 条应改、1 条建议，按当前内容不能合并。\n\n"
        "## 改动核对\n新增一份检查清单。\n"
    )
    staged = [
        "阻塞项：a",
        "应改项：b",
        "应改项：c",
        "应改项：d",
        "建议：e",
    ]
    out = reconcile_verdict_counts(body, staged)
    assert "评级 P3，1 条阻塞、3 条应改、1 条建议，按当前内容不能合并。" in out
    assert "2 条应改" not in out
    # Other sections are untouched.
    assert "## 改动核对\n新增一份检查清单。" in out


def test_reconcile_keeps_correct_verdict_verbatim() -> None:
    body = "## 结论\n评级 P0，无阻塞项，可以合并。\n\n## 验证\nlint 通过。\n"
    assert reconcile_verdict_counts(body, []) == body


def test_reconcile_correctly_counted_verdict_unchanged() -> None:
    body = "## 结论\n评级 P1，1 条阻塞、1 条应改。\n\n## 阻塞项\n- x\n"
    out = reconcile_verdict_counts(body, ["阻塞项：a", "应改项：b"])
    assert "评级 P1，1 条阻塞、1 条应改。" in out


def test_reconcile_leaves_body_without_verdict_section() -> None:
    body = "评级 P2，1 条阻塞。\n\n## 改动核对\n内容。\n"
    assert reconcile_verdict_counts(body, ["阻塞项：a"]) == body


def test_reconcile_handles_verdict_only_count_without_rank() -> None:
    body = "## 结论\n1 条阻塞、2 条应改。\n"
    # Without a rank the clause is ambiguous; leave the text untouched rather
    # than guessing where to splice the corrected tally.
    assert reconcile_verdict_counts(body, ["阻塞项：a", "应改项：b", "应改项：c"]) == body


def test_reconcile_no_findings_drops_count_clause() -> None:
    body = "## 结论\n评级 P0，1 条阻塞，可以合并。\n"
    out = reconcile_verdict_counts(body, [])
    assert "1 条阻塞" not in out
    assert "评级 P0，可以合并。" in out


def test_strip_ai_footer_removes_known_variants() -> None:
    assert strip_ai_footer("正文。\n\ngenerated by AI，工具 omp") == "正文。"
    assert strip_ai_footer("正文。\ngenerated by AI，工具 robomp") == "正文。"
    assert strip_ai_footer("正文。\n\nGenerated by AI with tool X") == "正文。"
    assert strip_ai_footer("正文，没有标记。") == "正文，没有标记。"


def test_strip_ai_footer_keeps_inline_mentions() -> None:
    body = "## 验证\n按作者报告的 generated by AI 结果记录。\n"
    # Only a footer line is stripped; a mid-sentence mention stays.
    assert "generated by AI" in strip_ai_footer(body)
