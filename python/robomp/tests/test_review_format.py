"""Unit tests for review summary rendering."""

from __future__ import annotations

from robomp.review_format import (
    count_severities,
    finding_line,
    format_counts,
    render_conclusion,
    render_findings_index,
    severity_of,
    stance,
    strip_ai_footer,
)


def test_severity_of_recognises_each_prefix() -> None:
    assert severity_of("阻塞项：第 42 行解引用空指针。") == "阻塞"
    assert severity_of("应改项：第 7 行用了加粗。") == "应改"
    assert severity_of("建议：第 11 行的概括与现状不符。") == "建议"
    assert severity_of("  阻塞项：缩进后仍算阻塞。") == "阻塞"


def test_severity_of_falls_back_to_should_fix() -> None:
    assert severity_of("这条评论没有写严重级别前缀。") == "应改"
    assert severity_of("") == "应改"


def test_count_severities_tallies_in_prompt_order() -> None:
    counts = count_severities(
        [
            "应改项：a",
            "阻塞项：b",
            "建议：c",
            "无前缀",
            "阻塞项：e",
        ]
    )
    assert counts == {"阻塞": 2, "应改": 2, "建议": 1}


def test_format_counts_omits_empty_severities() -> None:
    assert format_counts({"阻塞": 1, "应改": 0, "建议": 0}) == "1 条阻塞"
    assert format_counts({"阻塞": 0, "应改": 0, "建议": 0}) == ""
    assert format_counts({"阻塞": 2, "应改": 3, "建议": 1}) == "2 条阻塞、3 条应改、1 条建议"


def test_stance_request_changes_names_the_blocking_counts() -> None:
    assert stance("REQUEST_CHANGES", {"阻塞": 1, "应改": 2, "建议": 1}) == "改掉 1 条阻塞、2 条应改后可合并。"


def test_stance_request_changes_without_counts_still_withholds_merge() -> None:
    assert stance("REQUEST_CHANGES", {"阻塞": 0, "应改": 0, "建议": 0}) == "改掉下列各项后可合并。"


def test_stance_approve_mentions_advice_only() -> None:
    assert stance("APPROVE", {"阻塞": 0, "应改": 0, "建议": 2}) == "可以合并，另有 2 条建议不影响合并。"
    assert stance("APPROVE", {"阻塞": 0, "应改": 0, "建议": 0}) == "可以合并。"


def test_stance_comment_defers_to_maintainer() -> None:
    assert stance("COMMENT", {"阻塞": 0, "应改": 0, "建议": 0}) == "需要维护者决定是否纳入。"


def test_render_replaces_ranked_verdict_and_keeps_following_prose() -> None:
    body = (
        "## 结论\n"
        "评级 P1，1 条阻塞、2 条应改，按当前内容不能合并。上一轮意见已落实，但计数仍不一致。\n\n"
        "## 改动核对\n新增一份检查清单。\n"
    )
    out = render_conclusion(body, {"阻塞": 1, "应改": 3, "建议": 1}, "REQUEST_CHANGES")
    assert "改掉 1 条阻塞、3 条应改后可合并。上一轮意见已落实，但计数仍不一致。" in out
    assert "评级" not in out
    assert "P1" not in out
    assert "## 改动核对\n新增一份检查清单。" in out


def test_render_approve_without_findings() -> None:
    body = "## 结论\n评级 P0，无阻塞项，可以合并。\n\n## 静态核对\n未运行测试。\n"
    out = render_conclusion(body, {"阻塞": 0, "应改": 0, "建议": 0}, "APPROVE")
    assert "## 结论\n可以合并。" in out
    assert "评级" not in out
    assert "## 静态核对\n未运行测试。" in out


def test_render_leaves_body_without_conclusion_heading_alone() -> None:
    body = "## 改动核对\n内容。\n"
    assert render_conclusion(body, {"阻塞": 1, "应改": 0, "建议": 0}, "REQUEST_CHANGES") == body


def test_strip_ai_footer_removes_known_variants() -> None:
    assert strip_ai_footer("正文。\n\ngenerated by AI，工具 omp") == "正文。"
    assert strip_ai_footer("正文。\ngenerated by AI，工具 robomp") == "正文。"
    assert strip_ai_footer("正文。\n\nGenerated by AI with tool X") == "正文。"
    assert strip_ai_footer("正文，没有标记。") == "正文，没有标记。"


def test_strip_ai_footer_keeps_inline_mentions() -> None:
    body = "## 静态核对\n按作者报告的 generated by AI 结果记录。\n"
    # Only a footer line is stripped; a mid-sentence mention stays.
    assert "generated by AI" in strip_ai_footer(body)


def test_render_findings_index_replaces_model_section() -> None:
    body = (
        "## 结论\n\n改掉 1 条应改后可合并。\n\n## 改动\n一句话。\n\n"
        "## 意见\n\n1. 模型自己写的，会被替换\n\n## 未做\n未运行测试。\n"
    )
    out = render_findings_index(body, [("a/b.md", 6, "应改项：标题格式偏离 ADR 0057")])
    assert "模型自己写的" not in out
    assert "1. `a/b.md:6` 应改 标题格式偏离 ADR 0057" in out
    assert out.index("## 意见") < out.index("## 未做")


def test_render_findings_index_inserts_before_not_run() -> None:
    body = "## 结论\n\n可以合并。\n\n## 改动\n一句话。\n\n## 未做\n未运行测试。\n"
    out = render_findings_index(body, [("x.py", 3, "建议：命名")])
    assert out.index("## 意见") < out.index("## 未做")
    assert "`x.py:3` 建议 命名" in out


def test_finding_line_strips_prefix_and_truncates() -> None:
    long = "阻塞项：" + "很长的结论" * 20
    severity, summary = finding_line("p.md", 1, long)
    assert severity == "阻塞"
    assert not summary.startswith("阻塞项")
    assert summary.endswith("…") and len(summary) <= 61


def test_render_findings_index_noop_without_entries() -> None:
    body = "## 结论\n\n可以合并。\n"
    assert render_findings_index(body, []) == body
