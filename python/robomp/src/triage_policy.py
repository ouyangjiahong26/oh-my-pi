"""Repository-specific label and implementation policy.

Primary classifications select workflows. Repository templates and labels are
mapped separately so workflow vocabulary never leaks into GitHub metadata.
"""

from __future__ import annotations

import re
from typing import Protocol

CISLUNARSPACE = "cislunarspace"

ISSUE_TYPES = frozenset({"type/bug", "type/feature", "type/idea", "type/research", "type/task"})
ISSUE_AREAS = frozenset(
    {
        "area/content",
        "area/glossary",
        "area/references",
        "area/web",
        "area/ai-chat",
        "area/docs",
        "area/infra",
    }
)
PR_KINDS = frozenset({"kind/feature", "kind/bug-fix", "kind/doc", "kind/testing", "kind/cleanup", "kind/dependency"})

PRIMARY_TO_TYPE = {
    "bug": "type/bug",
    "documentation": "type/task",
    "enhancement": "type/feature",
    "proposal": "type/idea",
}
PR_TYPE_TO_KIND = {
    "feat": "kind/feature",
    "fix": "kind/bug-fix",
    "docs": "kind/doc",
    "test": "kind/testing",
    "refactor": "kind/cleanup",
    "perf": "kind/cleanup",
    "chore": "kind/cleanup",
    "ci": "kind/cleanup",
    "build": "kind/cleanup",
}


class _AuthorizedEvents(Protocol):
    def has_authorized_impl_event(self, issue_key: str) -> bool: ...


class _Bindings(Protocol):
    settings: object
    db: _AuthorizedEvents
    issue_key: str
    impl_authorized: bool


def policy_name(settings: object) -> str:
    """Read the configured policy without requiring a full Settings object."""
    if settings is None:
        return "upstream"
    return str(getattr(settings, "triage_policy", "upstream"))


def requires_authorization(settings: object) -> bool:
    """Whether this repository requires maintainer approval before implementation."""
    return policy_name(settings) == CISLUNARSPACE


def implementation_allowed(bindings: _Bindings) -> bool:
    """Allow implementation after the applicable authorization path succeeds."""
    if not requires_authorization(bindings.settings):
        if bindings.impl_authorized or bindings.db.has_authorized_impl_event(bindings.issue_key):
            return True
        row = bindings.db.get_issue(bindings.issue_key)
        return bool(row is not None and (row.pr_number is not None or row.classification in {"bug", "documentation"}))
    authorized = getattr(bindings.db, "has_authorized_impl_event", None)
    return bool(bindings.impl_authorized or (authorized is not None and authorized(bindings.issue_key)))


def labels_for_issue(primary: str, areas: list[str], existing_labels: list[str] | tuple[str, ...]) -> list[str]:
    """Fill only missing template types and evidence-backed areas.

    Existing template type and triage labels are preserved. Question, invalid,
    duplicate and wontfix do not imply a new issue type. Areas are optional
    because a wrong area is worse than no area.
    """
    existing = set(existing_labels)
    labels: list[str] = []
    if not existing.intersection(ISSUE_TYPES):
        type_label = PRIMARY_TO_TYPE.get(primary)
        if type_label is not None:
            labels.append(type_label)
    for area in areas:
        if area in ISSUE_AREAS and area not in existing and area not in labels:
            labels.append(area)
    return labels


def labels_for_pr(pr_type: str, areas: list[str]) -> list[str]:
    """Map a PR verdict type to this repository's PR kind and area labels."""
    kind = PR_TYPE_TO_KIND.get(pr_type)
    if kind is None:
        return []
    return [kind, *[area for area in dict.fromkeys(areas) if area in ISSUE_AREAS]]


def allowed_labels(labels: list[str], convention: str) -> list[str]:
    """Keep only labels defined by the repository's contribution guide."""
    if convention != CISLUNARSPACE:
        return labels
    allowed = (
        ISSUE_TYPES | ISSUE_AREAS | PR_KINDS | {"needs-triage", "needs-info", "ready-for-agent", "ready-for-human"}
    )
    return list(dict.fromkeys(label for label in labels if label in allowed))


def validate_pr_text(title: str, body: str, number: int, convention: str) -> str | None:
    """Return the first repository-specific PR metadata violation, if any."""
    if convention != CISLUNARSPACE:
        return None
    if not re.match(r"^\[AI Generated]\[(?:FEAT|FIX|DOC|TEST|CLEANUP|DEP)] \S", title):
        return "PR title must start with the AI-generated marker and kind, for example [AI Generated][FIX]."
    first_line = next((line.strip() for line in body.splitlines() if line.strip()), "")
    if not (first_line.lower().startswith("generated by ai") or first_line.startswith("工具")):
        return "The first PR-body line must name the generating tool, for example `generated by AI，工具 omp`."
    if not re.search(rf"(?m)^Closes #{number}\s*$", body):
        return f"PR body must contain a standalone `Closes #{number}` line."
    return None
